import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { businessIdentity } from '../src/config/businessIdentity';
import {
  aboutAudiences,
  aboutRouteCards,
  aboutStartingPoints,
  clearExpectations,
  innovationSteps,
  prototypeValues,
} from '../src/data/about';
import { retailVisibility } from '../src/config/retailVisibility';

let checks = 0;
const check = (condition: unknown, message: string) => {
  assert.ok(condition, message);
  checks += 1;
};

const placeholder = readFileSync(new URL('../app/[...path]/page.tsx', import.meta.url), 'utf8');
const sitemap = readFileSync(new URL('../app/sitemap.ts', import.meta.url), 'utf8');
const page = readFileSync(new URL('../app/about/page.tsx', import.meta.url), 'utf8');
const sections = readFileSync(new URL('../src/components/about/AboutSections.tsx', import.meta.url), 'utf8');
const data = readFileSync(new URL('../src/data/about.ts', import.meta.url), 'utf8');
const businessSource = readFileSync(new URL('../src/config/businessIdentity.ts', import.meta.url), 'utf8');
const siteSource = readFileSync(new URL('../src/config/site.ts', import.meta.url), 'utf8');
const layoutSource = readFileSync(new URL('../app/layout.tsx', import.meta.url), 'utf8');
const localServiceSource = readFileSync(new URL('../src/components/home/LocalServiceSection.tsx', import.meta.url), 'utf8');

check(!placeholder.includes("'about'"), '/about must no longer be generated by the catch-all placeholder.');
check(sitemap.includes("'/about'"), '/about must be included in the implemented sitemap route set.');
check(page.includes("robots: { index: true, follow: true }"), 'Completed About page must be indexable.');
check(page.includes('BreadcrumbList'), 'About page must include BreadcrumbList structured data.');
check(page.includes("canonical: '/about/'"), 'About page canonical route missing.');

check(businessIdentity.tradeName === 'ESHANTVA 3D Studio', 'Verified trade name changed unexpectedly.');
check(businessIdentity.constitution === 'Proprietorship', 'Verified business type changed unexpectedly.');
check(businessIdentity.gstin === '18DHLPG9662M1ZH', 'Verified GSTIN changed unexpectedly.');
check(businessIdentity.publicLocation === 'Biswanath, Assam, India', 'Approved public location changed unexpectedly.');
check(businessSource.includes("export const VERIFIED_PUBLIC_GSTIN = '18DHLPG9662M1ZH'"), 'GSTIN must remain centralized in businessIdentity.');
check(!data.includes('18DHLPG9662M1ZH'), 'About data must not duplicate the GSTIN literal.');
check(!sections.includes('18DHLPG9662M1ZH'), 'About components must read GSTIN from central business identity, not hardcode it.');
check(siteSource.includes("location: 'Biswanath, Assam, India'"), 'Site config must use the approved public location.');
const publicLocationSources = `${siteSource}\n${layoutSource}\n${localServiceSource}`;
for (const privateAddressPart of ['4th Part', 'Bam Gaon', '784176']) {
  check(!publicLocationSources.includes(privateAddressPart), `Private certificate/address detail exposed publicly: ${privateAddressPart}`);
}

check(aboutAudiences.map((item) => item.id).join(',') === 'students,makers,researchers,businesses', 'About page must preserve the four audience groups.');
check(aboutStartingPoints.length >= 8, 'Start With What You Have needs a useful range of starting points.');
check(prototypeValues.map((item) => item.title).join(',') === 'Shape,Fit,Layout,Enclosure,Presentation,Iteration', 'Prototype value topics changed unexpectedly.');
check(innovationSteps.map((item) => item.label).join(',') === 'Think,Build,Check,Improve', 'Innovation micro-journey must remain Think → Build → Check → Improve.');
check(clearExpectations.some((item) => item.includes('Not every custom request is automatically accepted')), 'Acceptance boundary missing.');
check(clearExpectations.some((item) => item.includes('Production begins only after')), 'Production-start boundary missing.');

for (const route of [...(retailVisibility.isInternal ? ['/shop'] : []), '/custom-order', '/bulk-order']) {
  check(aboutRouteCards.some((item) => item.href === route), `Missing customer route ${route}.`);
}
for (const route of ['/services', '/how-it-works', '/our-work', '/faq']) {
  check(sections.includes(`href="${route}"`) || sections.includes(`to="${route}"`), `Missing About cross-link ${route}.`);
}

for (const phrase of [
  'Ideas deserve a practical first step.',
  'Making the first physical step easier to approach.',
  'You do not need everything figured out before you begin.',
  'Based in Biswanath, Assam.',
  'Good projects often need more than one kind of expertise.',
  'Trust should come from verified facts, not inflated claims.',
  'FROM IDEA TO PHYSICAL PRODUCT.',
]) check(sections.includes(phrase), `Required About phrase missing: ${phrase}`);

const publicText = `${page}\n${sections}\n${data}`.toLowerCase();
const forbiddenClaims = [
  'best 3d', 'leading 3d', 'industry-leading', 'trusted by', 'years of experience',
  'professional engineers', 'the only service', 'first in biswanath', 'largest',
  'assam lacks innovation', 'students lack interest', 'no innovation culture',
  'institutions do not support', 'cheapest', 'lowest price', 'save 50%',
];
for (const term of forbiddenClaims) check(!publicText.includes(term), `Unsupported or negative public claim found: ${term}`);

const operationalTerms = [
  'purchaseprice', 'stockkg', 'reorder threshold', 'printer model', 'machine count',
  'nozzle size', 'layer height', 'infill percentage', 'print speed', 'filament supplier',
  'production capacity', 'scanner availability', 'business margins',
];
for (const term of operationalTerms) check(!publicText.includes(term), `Operational detail leaked into About: ${term}`);

for (const term of ['founder is a researcher', 'founder is an innovator', 'meet the team', 'our milestones', 'our partners']) {
  check(!publicText.includes(term), `Invented identity/history framing found: ${term}`);
}

check(!/iit|university logo|government logo|startup logo/.test(publicText), 'About page must not fabricate institution/partner relationships.');
check(!/trade licence|trade license/.test(publicText), 'Trade Licence details should not be published on About.');
check(!/\bcertified\b/.test(publicText), 'About page must not claim certification.');

const placeholderRoutes = ['faq', 'how-it-works', 'our-work'];
for (const implemented of placeholderRoutes) check(!new RegExp(`['\"]${implemented}['\"]`).test(placeholder), `${implemented} must remain outside the catch-all placeholder.`);
check(sitemap.includes("'/how-it-works'"), 'Page 9 sitemap entry must remain.');
check(sitemap.includes("'/faq'"), 'Page 10 sitemap entry must remain.');
check(sitemap.includes('portfolioIsLive'), 'Page 8 portfolio sitemap gate must remain.');

console.log(`About static checks passed: ${checks}`);
