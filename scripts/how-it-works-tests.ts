import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { customerPaths, routeDecisions } from '../src/data/howItWorks';
import { getFaqsByIds, howItWorksFaqIds } from '../src/data/faqs';
import { businessIdentity } from '../src/config/businessIdentity';
import { pathToProduct } from '../src/data/pathToProduct';
import { retailVisibility } from '../src/config/retailVisibility';

assert.deepEqual(customerPaths.map((path) => path.id), retailVisibility.isInternal ? ['shop', 'custom', 'bulk'] : ['custom', 'bulk'], 'Public mode must hide the Shop path while internal mode preserves it.');
assert.equal(new Set(customerPaths.map((path) => path.anchor)).size, customerPaths.length, 'Customer-path anchors must be unique.');
assert.ok(customerPaths.every((path) => path.steps.length >= 6), 'Each customer path needs a useful step sequence.');
assert.deepEqual(pathToProduct.map((step) => step.title), ['Start', 'Define', 'Prepare', 'Review', 'Produce', 'Deliver'], 'Page 6 Path-to-Product vocabulary must remain canonical.');
assert.equal(businessIdentity.gstin, '18DHLPG9662M1ZH', 'Shared business identity must emit the verified GSTIN.');
const processFaqs = getFaqsByIds(howItWorksFaqIds);
assert.ok(processFaqs.some((faq) => faq.question === 'Is COD available?' && /not available/i.test(faq.answer)), 'COD rule must be explicit and truthful.');
assert.ok(routeDecisions.some((item) => item.href === '/custom-order'), 'Decision section must link to Custom Order.');
assert.ok(routeDecisions.some((item) => item.href === '/bulk-order'), 'Decision section must link to Bulk Order.');

const placeholder = readFileSync('app/[...path]/page.tsx', 'utf8');
assert.doesNotMatch(placeholder, /['\"]how-it-works['\"]/, 'How It Works must no longer be generated by the placeholder catch-all.');

const sitemap = readFileSync('app/sitemap.ts', 'utf8');
assert.match(sitemap, /['\"]\/how-it-works['\"]/, 'How It Works must be eligible for sitemap inclusion.');

const page = readFileSync('app/how-it-works/page.tsx', 'utf8');
assert.match(page, /robots:\s*\{\s*index:\s*true,\s*follow:\s*true\s*\}/, 'Completed Page 9 must be indexable.');
assert.match(page, /BreadcrumbList/, 'Page 9 must include breadcrumb structured data.');

const sections = readFileSync('src/components/how-it-works/HowItWorksSections.tsx', 'utf8');
for (const phrase of ['A clear path from request to physical result.', 'How are you starting?', 'When is pricing confirmed?', 'COD is not available.', 'Follow the order after confirmation.']) {
  assert.ok(sections.includes(phrase), `Missing required Page 9 phrase: ${phrase}`);
}
for (const forbidden of ['purchasePrice', 'spool', 'reorder URL', 'nozzle size', 'layer height', 'infill percentage', 'print speed']) {
  assert.ok(!sections.toLowerCase().includes(forbidden.toLowerCase()), `Page 9 leaks forbidden operational detail: ${forbidden}`);
}

console.log('How It Works tests passed.');
